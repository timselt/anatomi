// Görev cümlesi: yapının türüne göre kısa açıklama (ayrıntılı görev henüz eklenmedi).
function gorev(en, la) {
  if (/^hepatovenous segment/.test(en)) return 'Karaciğerin Couinaud sınıflamasına göre bir segmentidir. Her segmentin kendi portal ven dalı, arteri ve safra kanalı vardır; cerrahide ayrı ayrı çıkarılabilir. I. segment kuyruklu lobdur; II-IV sol, V-VIII sağ karaciğerdedir.';
  const dalMi = /^(Ramus|Rami|Pars|Tributaria)/.test(la);
  if (/ artery|arteria|arch$| arch of| trunk$/.test(en) || /^Arter|^Arcus palmaris|^Arcus plantaris|^Truncus (costo|thyro)/.test(la)) {
    return dalMi ? 'Bir arterin dalı ya da bölümüdür; bağlı olduğu bölgeye oksijenli kan taşır.' : 'Arterdir; adının gösterdiği bölgeye oksijenli kan taşır.';
  }
  if (/ vein|venous|hepatovenous/.test(en)) return dalMi ? 'Bir venin dalı ya da bölümüdür; bölgenin kanını toplar.' : 'Vendir; adının gösterdiği bölgenin kanını kalbe doğru toplar.';
  if (/^(Musculus|Musculi|Caput|Pars)/.test(la)) return 'İskelet kasıdır (ya da bir kasın başı/bölümü). Başlangıç, sonlanma, sinir ve görev bilgisi henüz eklenmedi.';
  return 'Bağ dokusu yapısıdır; komşu yapıları birbirine bağlar ya da destekler.';
}

